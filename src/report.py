"""Build docs/results.md (and a copy of the raw rows) from outputs/results.jsonl.

  python src/report.py
If a run name appears more than once, the latest row wins.
"""
from __future__ import annotations

import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "outputs" / "results.jsonl"
DOCS = ROOT / "docs"


def load(path: Path = SRC) -> list[dict]:
    rows: dict[str, dict] = {}
    for line in path.read_text().splitlines():
        if line.strip():
            r = json.loads(line)
            rows[r["run"]] = r
    return list(rows.values())


def _fmt(x, pct=False, digits=3):
    if x is None:
        return "n/a"
    return f"{x * 100:.1f}%" if pct else f"{x:.{digits}g}" if isinstance(x, float) else str(x)


def table(rows: list[dict]) -> str:
    rows = sorted(rows, key=lambda r: -r.get("macro_f1", 0))
    out = ["| Run | Approach | Model | n | Macro-F1 | Accuracy | Invalid | p50 / p95 latency (s) | $ per 1k predictions | Hardware |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        cost = r.get("usd_per_1k")
        out.append("| {run} | {ap} | {model} | {n} | **{f1:.3f}** | {acc} | {inv} | {p50} / {p95} | {cost} | {hw} |".format(
            run=r["run"], ap=r.get("approach", ""), model=r.get("model", ""), n=r.get("n", ""),
            f1=r.get("macro_f1", 0), acc=_fmt(r.get("accuracy"), pct=True), inv=_fmt(r.get("invalid_rate"), pct=True),
            p50=_fmt(r.get("p50_latency_s")), p95=_fmt(r.get("p95_latency_s")),
            cost="n/a" if cost is None else f"${cost:.4f}", hw=r.get("hardware", "2 vCPU sandbox")))
    return "\n".join(out)


def main() -> None:
    rows = load()
    DOCS.mkdir(exist_ok=True)
    md = ["# Results: Banking77 intent classification", "",
          "Generated by `src/report.py` from `outputs/results.jsonl` (raw rows copied to `docs/results.jsonl`). "
          "All runs use the same golden test slice; see the README for setup and cost assumptions.", "",
          table(rows), ""]
    (DOCS / "results.md").write_text("\n".join(md))
    shutil.copy(SRC, DOCS / "results.jsonl")
    print("\n".join(md))


if __name__ == "__main__":
    main()
